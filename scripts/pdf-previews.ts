/**
 * Regenerates the list of PDFs that have a first-page preview.
 *
 *   npm run previews:pdf
 *
 * Previews live in public/img/pdf/<docId>.jpg and are produced from the
 * document's first page (pdftoppm). The manifest is committed so the app never
 * has to probe the filesystem at runtime — `public/` is served statically and
 * is not reliably readable from a serverless function.
 */
import { readdirSync, writeFileSync } from "node:fs";

const files = readdirSync("public/img/pdf").filter((f) => f.endsWith(".jpg"));
const ids = files.map((f) => f.replace(/\.jpg$/, "")).sort();

const body = `/**
 * Generated by scripts/pdf-previews.ts — do not edit by hand.
 *
 * Documents in this list have a first-page JPEG at public/img/pdf/<id>.jpg,
 * shown as a preview on the resource card and in the home page list.
 */
export const PDF_PREVIEW_IDS = new Set<string>([
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
]);

/** Preview image URL for a document, or undefined when there is none. */
export function pdfPreviewUrl(docId: string): string | undefined {
  return PDF_PREVIEW_IDS.has(docId) ? \`/img/pdf/\${docId}.jpg\` : undefined;
}
`;

writeFileSync("lib/pdf-previews.ts", body);
console.log(`wrote lib/pdf-previews.ts with ${ids.length} previews`);
